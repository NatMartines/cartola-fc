-- 01 · Ambiente do projeto Cartola FC
-- Rodar com ACCOUNTADMIN (tarefa administrativa). No dia a dia, usar a role CARTOLA_DEV.

USE ROLE ACCOUNTADMIN;

-- Warehouse próprio do projeto, com trava de custo
CREATE WAREHOUSE IF NOT EXISTS WH_CARTOLA
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_CARTOLA
  WITH CREDIT_QUOTA = 10
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 75 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE WH_CARTOLA SET RESOURCE_MONITOR = RM_CARTOLA;

-- Database e camadas
CREATE DATABASE IF NOT EXISTS CARTOLA;
CREATE SCHEMA IF NOT EXISTS CARTOLA.RAW;
CREATE SCHEMA IF NOT EXISTS CARTOLA.STAGING;
CREATE SCHEMA IF NOT EXISTS CARTOLA.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS CARTOLA.MARTS;

-- Role do projeto (menor privilégio)
CREATE ROLE IF NOT EXISTS CARTOLA_DEV;
GRANT USAGE ON WAREHOUSE WH_CARTOLA TO ROLE CARTOLA_DEV;
GRANT USAGE ON DATABASE CARTOLA TO ROLE CARTOLA_DEV;
GRANT CREATE SCHEMA ON DATABASE CARTOLA TO ROLE CARTOLA_DEV;  -- o Elementary cria o schema ELEMENTARY
GRANT ALL ON SCHEMA CARTOLA.RAW TO ROLE CARTOLA_DEV;
GRANT ALL ON SCHEMA CARTOLA.STAGING TO ROLE CARTOLA_DEV;
GRANT ALL ON SCHEMA CARTOLA.SNAPSHOTS TO ROLE CARTOLA_DEV;
GRANT ALL ON SCHEMA CARTOLA.MARTS TO ROLE CARTOLA_DEV;
GRANT CREATE STREAMLIT ON SCHEMA CARTOLA.MARTS TO ROLE CARTOLA_DEV;
GRANT ROLE CARTOLA_DEV TO USER NATMARTINES;
GRANT ROLE CARTOLA_DEV TO ROLE SYSADMIN;
